function variants(productId: string, colors: { name: string; hex: string }[]): Variant[] {
  return colors.flatMap((color, colorIndex) => ['P', 'M', 'G'].map((size, sizeIndex) => ({
    id: `${productId}-${colorIndex + 1}-${size.toLowerCase()}`,
    size,
    color: color.name,
    colorHex: color.hex,
    stock: [5, 8, 4][sizeIndex] + colorIndex,
  })));
}

